#pragma once

// 5x7 bitmap glyphs for the temperature overlay: digits, '.', '-', ' ', 'C',
// 'F' and the degree sign (encoded as '\xB0'). Each glyph is 7 rows of 5 bits,
// most significant of the 5 bits leftmost.

#include <cstdint>

namespace esphome {
namespace overlay {

static constexpr int GLYPH_W = 5;
static constexpr int GLYPH_H = 7;
static constexpr int GLYPH_ADVANCE = 6;  // glyph plus one column of spacing

// Returns the glyph rows for `c`, or nullptr if the font has no glyph for it.
inline const uint8_t *glyph_rows(char c) {
  static const uint8_t DIGITS[10][GLYPH_H] = {
      {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E},  // 0
      {0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E},  // 1
      {0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F},  // 2
      {0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E},  // 3
      {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02},  // 4
      {0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E},  // 5
      {0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E},  // 6
      {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08},  // 7
      {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E},  // 8
      {0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C},  // 9
  };
  static const uint8_t DOT[GLYPH_H] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C};
  static const uint8_t MINUS[GLYPH_H] = {0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00};
  static const uint8_t SPACE[GLYPH_H] = {0, 0, 0, 0, 0, 0, 0};
  static const uint8_t LETTER_C[GLYPH_H] = {0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E};
  static const uint8_t LETTER_F[GLYPH_H] = {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10};
  static const uint8_t DEGREE[GLYPH_H] = {0x0C, 0x12, 0x12, 0x0C, 0x00, 0x00, 0x00};
  if (c >= '0' && c <= '9')
    return DIGITS[c - '0'];
  switch (c) {
    case '.':
      return DOT;
    case '-':
      return MINUS;
    case ' ':
      return SPACE;
    case 'C':
      return LETTER_C;
    case 'F':
      return LETTER_F;
    case '\xB0':
      return DEGREE;
    default:
      return nullptr;
  }
}

}  // namespace overlay
}  // namespace esphome
